"""
Unified AI Output Security Guard for ResearchLens.

Applies deterministic post-generation security policy across all four AI workflows:
1. Research Assistant Q&A
2. Paper Summary Generation
3. Paper Comparison Synthesis
4. Research Evolution & Gap Discovery

Guarantees:
- Blocks attack canary tokens (e.g. 'HACKED').
- Blocks database connection URIs and credential assignments.
- Blocks configuration/environment variable identifiers (DATABASE_URL, POSTGRES_PASSWORD, etc.).
- Blocks raw JWT tokens.
- Eliminates echoed credential names or infrastructure refusal phrases.
- Preserves legitimate academic discussion of security/passwords backed by verified evidence.
- Preserves scholarly evidence citations ([ev-1], [P1], etc.).
- Fails safe on unexpected errors without exposing sensitive candidate output.
- Never logs sensitive or rejected content.
"""
import re
from typing import Any, List, Optional, Tuple

from app.core.logging import get_logger

logger = get_logger(__name__)

SAFE_CANONICAL_REFUSAL = "The available catalog evidence is insufficient to conclusively answer this question."

# Regex patterns for deterministic post-generation security guard
_RE_ATTACK_CANARY = re.compile(r"\bHACKED\b", re.IGNORECASE)
_RE_CONNECTION_URI = re.compile(r"\b(?:postgres(?:ql)?|mysql|sqlite|mongodb|redis):\/\/[^\s]+", re.IGNORECASE)
_RE_CONFIG_IDENTIFIERS = re.compile(
    r"\b(?:DATABASE_URL|POSTGRES_PASSWORD|JWT_SECRET|SECRET_KEY|POSTGRES_USER|POSTGRES_DB|GROQ_API_KEY)\b",
    re.IGNORECASE
)
_RE_CREDENTIAL_ASSIGNMENTS = re.compile(
    r"\b(?:password|passwd|pwd|secret_key|jwt_secret)\s*(?:is|\:|\=|\:\=|\=)\s*[:=]?\s*['\"]?[^\s'\".,;]{4,}",
    re.IGNORECASE
)
_RE_JWT_TOKEN = re.compile(r"\beyJ[A-Za-z0-9_-]{10,}\.[A-Za-z0-9_-]{10,}\.[A-Za-z0-9_-]{10,}\b")
_RE_REFUSAL_INFRASTRUCTURE = re.compile(
    r"\b(?:database_url|postgres_password|secret\s+jwt\s+key|jwt\s+key|database\s+credentials|"
    r"database\s+password|postgres\s+password|system\s+credentials|system\s+passwords?|"
    r"administrative\s+passwords?|admin\s+passwords?)\b",
    re.IGNORECASE
)


def enforce_ai_output_security_guard(
    content: str,
    evidence: Optional[List[Any]] = None,
    question: Optional[str] = None,
    fallback_text: Optional[str] = None,
    workflow_name: str = "assistant"
) -> Tuple[str, bool]:
    """
    Deterministic post-generation output guard for AI-generated text across all workflows.

    Args:
        content: Candidate text generated by an AI model.
        evidence: Optional list of evidence items, strings, or passages backing the output.
        question: Optional user inquiry or prompt.
        fallback_text: Optional text to substitute upon rejection (defaults to SAFE_CANONICAL_REFUSAL).
        workflow_name: Name of workflow ('assistant', 'summary', 'comparison', 'evolution') for logging.

    Returns:
        (sanitized_content: str, was_modified: bool)
    """
    replacement = fallback_text if fallback_text is not None else SAFE_CANONICAL_REFUSAL

    if not content:
        return content, False

    try:
        # Check 1: Attack canary token 'HACKED'
        if _RE_ATTACK_CANARY.search(content):
            logger.warning("AI output security guard triggered in %s: attack canary detected; enforcing safe replacement.", workflow_name)
            return replacement, True

        # Check 2: Connection URI (e.g. postgresql://user:pass@host/db)
        if _RE_CONNECTION_URI.search(content):
            logger.warning("AI output security guard triggered in %s: connection URI pattern detected; enforcing safe replacement.", workflow_name)
            return replacement, True

        # Check 3: Configuration / environment variable identifiers
        if _RE_CONFIG_IDENTIFIERS.search(content):
            logger.warning("AI output security guard triggered in %s: configuration identifier detected; enforcing safe replacement.", workflow_name)
            return replacement, True

        # Check 4: Credential assignments (e.g. password: xyz)
        if _RE_CREDENTIAL_ASSIGNMENTS.search(content):
            logger.warning("AI output security guard triggered in %s: credential assignment detected; enforcing safe replacement.", workflow_name)
            return replacement, True

        # Check 5: JWT tokens
        if _RE_JWT_TOKEN.search(content):
            logger.warning("AI output security guard triggered in %s: JWT token pattern detected; enforcing safe replacement.", workflow_name)
            return replacement, True

        # Check 6: Echoing credential or infrastructure refusal phrases
        if _RE_REFUSAL_INFRASTRUCTURE.search(content):
            logger.warning("AI output security guard triggered in %s: infrastructure credential refusal echo detected; enforcing safe replacement.", workflow_name)
            return replacement, True

        # Check 7: Generic "password" or "postgres" in non-evidence refusal context
        c_lower = content.lower()
        if "password" in c_lower or "postgres" in c_lower:
            has_grounded_evidence = False
            if evidence:
                for ev in evidence:
                    passage = ""
                    if isinstance(ev, str):
                        passage = ev
                    elif hasattr(ev, "source_passage"):
                        passage = ev.source_passage or ""
                    elif hasattr(ev, "claim"):
                        passage = ev.claim or ""
                    elif isinstance(ev, dict):
                        passage = ev.get("source_passage", "") or ev.get("abstract", "") or ev.get("text", "") or ev.get("title", "")
                    if "password" in passage.lower() or "postgres" in passage.lower():
                        has_grounded_evidence = True
                        break

            if not has_grounded_evidence:
                refusal_cues = ["insufficient", "do not provide", "cannot reveal", "not found", "no information", "credentials", "database", "system"]
                if any(cue in c_lower for cue in refusal_cues):
                    logger.warning("AI output security guard triggered in %s: ungrounded credential refusal mention; enforcing safe replacement.", workflow_name)
                    return replacement, True

        return content, False

    except Exception as exc:
        logger.error("Error during AI output security guard evaluation in %s: %s; failing safe.", workflow_name, exc)
        return replacement, True
